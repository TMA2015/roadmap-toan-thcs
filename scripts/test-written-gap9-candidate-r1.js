#!/usr/bin/env node
"use strict";
// Review-only candidate package QA; live catalog and historical QA must remain unchanged.
const fs=require("node:fs"),crypto=require("node:crypto"),assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8");
const raw=read("docs/assets/data/written-exercises/written-exercise-library-v1.json");
const originalSha=crypto.createHash("sha1").update("blob "+Buffer.byteLength(raw)+"\0").update(raw).digest("hex");
assert.equal(originalSha,"5141a40bf1b8f8763257857d3b805d681a0956fa","original 75 catalog must remain byte-for-byte");
const canonical=JSON.parse(raw);
assert.equal(canonical.exercises.length,75,"candidate is not yet released");
assert.equal(canonical.published_scope.exercise_count,75,"candidate must not claim publication");
assert.equal(canonical.auto_readiness_credit,false);
assert.equal(canonical.self_marking_only,true);
const stage=JSON.parse(read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-STRUCTURED_CANDIDATES.json"));
assert.equal(stage.status,"ACADEMIC_PASS_OWNER_RELEASE_PENDING");
assert.equal(stage.authorization,"REVIEW_ONLY_NO_DEPLOY");
assert.equal(stage.source_catalog_blob_sha,originalSha);
assert.equal(stage.original_published_count,75);
assert.equal(stage.candidate_count,9);
assert.equal(stage.candidates.length,9);
const packet=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-AUTHORING-REVIEW.md");
const receipt=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-NOTEBOOKLM_OWNER_VERDICT.md");
assert(receipt.includes("PACKET_ID|MATH-WRITTEN-GAP9-20261023-R0"));
assert(receipt.includes("SOURCE_BLOB|5141a40bf1b8f8763257857d3b805d681a0956fa"));
assert(receipt.includes("EXPECTED|9")&&receipt.includes("REVIEWED|9")&&receipt.includes("OVERALL|PASS"));
assert(receipt.includes("AUTHORIZATION|REVIEW_ONLY_NO_DEPLOY"),"verdict cannot authorize deployment");
const ids=["WX02-NUM-005","WX02-NUM-006","WX03-RAT-003","WX14-TRI-004","WX24-MOD-003","WX20-GEO-004","WX21-STA-003","WX19-CIR-005","WX20-GEO-005"];
const candidateIds=["CAND-G6-01","CAND-G6-02","CAND-G7-01","CAND-G7-02","CAND-G8-01","CAND-G8-02","CAND-G9-01","CAND-G9-02","CAND-G9-03"];
assert.deepEqual(stage.candidates.map(x=>x.exercise_id),ids,"candidate order");
assert.equal(new Set(canonical.exercises.map(x=>x.exercise_id).concat(ids)).size,84,"candidate IDs do not collide with historic 75");
for(const id of candidateIds)assert(receipt.includes("ITEM|"+id+"|PASS"),"missing review PASS "+id);
const headings=[...packet.matchAll(/^## (G[6789]-0[123]) — ([^\n]+)$/gm)];
assert.equal(headings.length,9,"exact source item count");
for(let i=0;i<9;i++){
 const x=stage.candidates[i],h=headings[i];
 const section=packet.slice(h.index+h[0].length,headings[i+1]?.index??packet.indexOf("## CROSS-ITEM",h.index));
 const problem=section.match(/\*\*Đề bài\.\*\*\s*([\s\S]*?)\n\n\*\*Gợi ý/);
 const sol=section.match(/\*\*Lời giải(?: kiểm tra nội bộ)?\.\*\*\s*([\s\S]*?)(?=\n\n\*\*(?:Vì sao cách này|Rubric \/))/);
 assert(problem&&sol,"could not parse reviewed text "+x.exercise_id);
 assert.equal(x.problem_markdown,problem[1].trim(),"verbatim reviewed problem "+x.exercise_id);
 assert.equal(x.full_solution_markdown,sol[1].trim(),"verbatim reviewed solution "+x.exercise_id);
 assert.equal(x.exercise_kind,"anchor");
 assert(x.hint_steps.length>=2&&x.hint_steps.length<=3,"reviewed staged hints "+x.exercise_id);
 assert.equal(x.rubric.reduce((sum,r)=>sum+r.points,0),x.rubric_total,"rubric sum");
 assert(x.common_mistakes.length>=3,"mistake coverage");
 assert(x.remediation_links.length>=2,"remediation");
 assert.equal(x.academic_review?.packet_id,"MATH-WRITTEN-GAP9-20261023-R0");
 assert.equal(x.academic_review?.status,"APPROVED");
 assert.equal(x.academic_review?.publication_gate,"PENDING_OWNER_RELEASE");
 assert.equal(x.gates_core,false);
 assert.equal(x.auto_readiness_credit,false);
 if(x.level==="ENTRANCE10")assert(!x.kntt_placements,"exam transfer must not imply school placement");
 else assert(x.kntt_placements?.length===1&&x.kntt_placements[0].grade===x.grade_overlay[0],"S1 grade placement");
}
const overlay=JSON.parse(read("docs/assets/data/written-exercises/written-p2-hints-overlay-v1.json"));
assert.equal(overlay.source_catalog_blob_sha,originalSha,"previously released three P2 hints must stay source-locked");
assert.equal(overlay.source_catalog_exercise_count,75);
assert.equal(overlay.changes.length,3);
console.log("PASS GAP9: 9 reviewed staged items, exact source text, no publication, original 75 and 3 old P2 hints byte-preserved");

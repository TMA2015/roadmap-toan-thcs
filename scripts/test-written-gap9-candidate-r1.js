#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),crypto=require("node:crypto"),assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8");
const raw=read("docs/assets/data/written-exercises/written-exercise-library-v1.json");
const deployedSha=crypto.createHash("sha1").update("blob "+Buffer.byteLength(raw)+"\0").update(raw).digest("hex");
const canonical=JSON.parse(raw),old=canonical.exercises.slice(0,75);
assert.equal(canonical.exercises.length,84);
assert.equal(canonical.published_scope.exercise_count,84);
assert.equal(canonical.auto_readiness_credit,false);
assert.equal(canonical.self_marking_only,true);
let h=0xcbf29ce484222325n;
const history=JSON.stringify(old);
for(let i=0;i<history.length;i++)h=BigInt.asUintN(64,(h^BigInt(history.charCodeAt(i)))*0x100000001b3n);
assert.equal(h.toString(16).padStart(16,"0"),"a57d3ca82843d506","all 75 historical records must remain identical");
const st=JSON.parse(read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-STRUCTURED_CANDIDATES.json"));
assert.equal(st.source_catalog_blob_sha,"5141a40bf1b8f8763257857d3b805d681a0956fa");
assert.equal(st.authorization,"REVIEW_ONLY_NO_DEPLOY","reviewer's independent approval was academic only");
assert.equal(st.candidate_count,9);
const p=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-AUTHORING-REVIEW.md");
const v=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-NOTEBOOKLM_OWNER_VERDICT.md");
assert(v.includes("EXPECTED|9")&&v.includes("REVIEWED|9")&&v.includes("OVERALL|PASS")&&v.includes("AUTHORIZATION|REVIEW_ONLY_NO_DEPLOY"));
const ids=["WX02-NUM-005","WX02-NUM-006","WX03-RAT-003","WX14-TRI-004","WX24-MOD-003","WX20-GEO-004","WX21-STA-003","WX19-CIR-005","WX20-GEO-005"];
const cids=["CAND-G6-01","CAND-G6-02","CAND-G7-01","CAND-G7-02","CAND-G8-01","CAND-G8-02","CAND-G9-01","CAND-G9-02","CAND-G9-03"];
assert.deepEqual(canonical.exercises.slice(75).map(x=>x.exercise_id),ids);
assert.equal(new Set(canonical.exercises.map(x=>x.exercise_id)).size,84);
assert.deepEqual(st.candidates.map(x=>x.exercise_id),ids);
const headings=[...p.matchAll(/^## (G[6789]-0[123]) — ([^\n]+)$/gm)];assert.equal(headings.length,9);
for(let i=0;i<9;i++){
 const x=canonical.exercises[i+75],c=st.candidates[i],header=headings[i],b=p.slice(header.index+header[0].length,headings[i+1]?.index??p.indexOf("## CROSS-ITEM",header.index));
 const q=b.match(/\*\*Đề bài\.\*\*\s*([\s\S]*?)\n\n\*\*Gợi ý/);
 const s=b.match(/\*\*Lời giải(?: kiểm tra nội bộ)?\.\*\*\s*([\s\S]*?)(?=\n\n\*\*(?:Vì sao cách này|Rubric \/))/);
 assert(q&&s,"source parse "+x.exercise_id);
 assert.equal(x.problem_markdown,q[1].trim(),"published exact review text "+x.exercise_id);
 assert.equal(x.full_solution_markdown,s[1].trim(),"published exact worked solution "+x.exercise_id);
 assert.deepEqual(x.hint_steps,c.hint_steps,"published same approved hint ladder "+x.exercise_id);
 assert.deepEqual(x.rubric,c.rubric,"published same approved rubric "+x.exercise_id);
 assert.deepEqual(x.common_mistakes,c.common_mistakes,"published same approved error guidance "+x.exercise_id);
 assert.equal(x.academic_review?.publication_gate,"OWNER_RELEASE_APPROVED_20261023","explicit owner release approval");
 assert(v.includes("ITEM|"+cids[i]+"|PASS"),"reviewed 9/9 "+cids[i]);
 assert(x.hint_steps.length===2||x.hint_steps.length===3);
 assert.equal(x.rubric.reduce((t,r)=>t+r.points,0),x.rubric_total);
 assert.equal(x.gates_core,false);
 assert.equal(x.auto_readiness_credit,false);
 if(x.level==="ENTRANCE10")assert(!x.kntt_placements,"Entrance10 no falsely assigned school lesson");
 else assert.equal(x.kntt_placements[0].grade,x.grade_overlay[0],"S1 placement");
}
const fig=canonical.exercises.find(x=>x.exercise_id==="WX14-TRI-004");
assert(fig.figure_uri&&fs.existsSync("docs/"+fig.figure_uri.replace(/^\.\.\//,"")),"G7 multi-step figure with stated hypotheses only");
const batch=canonical.published_scope.batches.find(x=>x.batch_id==="GAP9_NEW_STRUCTURES_20261023");
assert(batch?.status==="PUBLISHED"&&batch.count===9&&batch.owner_release_authorization==="OWNER_APPROVED_RELEASE_20261023");
const overlay=JSON.parse(read("docs/assets/data/written-exercises/written-p2-hints-overlay-v1.json"));
assert.equal(overlay.source_catalog_blob_sha,deployedSha,"previous P2 hints must match published catalog");
assert.equal(overlay.source_catalog_exercise_count,84);
assert.equal(overlay.source_catalog_snapshot_date,canonical.snapshot_date);
assert.deepEqual(overlay.changes.map(x=>x.exercise_id).sort(),["WX07-RAT-001","WX16-QUAD-001","WX19-CIR-002"].sort());
console.log("PASS GAP9 release: 84 canonical with 75 frozen, 9 exact reviewed originals, owner authorization, geometry diagram and 3 legacy P2 hint ladders");

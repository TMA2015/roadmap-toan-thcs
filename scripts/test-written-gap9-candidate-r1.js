#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8");
const data=JSON.parse(read("docs/assets/data/written-exercises/written-exercise-library-v1.json"));
const packet=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-AUTHORING-REVIEW.md");
const receipt=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP9-20261023-NOTEBOOKLM_OWNER_VERDICT.md");
assert.equal(data.exercises.length,84,"75 existing + 9 independent reviewed items only");
assert.equal(data.published_scope.exercise_count,84,"staged catalog count");
assert.equal(data.auto_readiness_credit,false);
assert.equal(data.self_marking_only,true);
const initial=JSON.stringify(data.exercises.slice(0,75));
let h=0xcbf29ce484222325n;
for(let i=0;i<initial.length;i++) h=BigInt.asUintN(64,(h^BigInt(initial.charCodeAt(i)))*0x100000001b3n);
assert.equal(h.toString(16).padStart(16,"0"),"a57d3ca82843d506","source-locked historical 75 records drifted");
const ids=["WX02-NUM-005","WX02-NUM-006","WX03-RAT-003","WX14-TRI-004","WX24-MOD-003","WX20-GEO-004","WX21-STA-003","WX19-CIR-005","WX20-GEO-005"];
const cand=["CAND-G6-01","CAND-G6-02","CAND-G7-01","CAND-G7-02","CAND-G8-01","CAND-G8-02","CAND-G9-01","CAND-G9-02","CAND-G9-03"];
assert.deepEqual(data.exercises.slice(75).map(x=>x.exercise_id),ids,"append ordered, no rewrites");
assert.equal(new Set(data.exercises.map(x=>x.exercise_id)).size,84,"unique IDs");
assert(receipt.includes("PACKET_ID|MATH-WRITTEN-GAP9-20261023-R0"));
assert(receipt.includes("SOURCE_BLOB|5141a40bf1b8f8763257857d3b805d681a0956fa"));
assert(receipt.includes("EXPECTED|9")&&receipt.includes("REVIEWED|9")&&receipt.includes("OVERALL|PASS"));
assert(receipt.includes("AUTHORIZATION|REVIEW_ONLY_NO_DEPLOY"),"independent report did not authorize release");
for(const cid of cand)assert(receipt.includes("ITEM|"+cid+"|PASS"),"verdict ID missing "+cid);
const headings=[...packet.matchAll(/^## (G[6789]-0[123]) — ([^\n]+)$/gm)];
assert.equal(headings.length,9,"exact author packet count");
for(let i=0;i<9;i++){
 const x=data.exercises[75+i],header=headings[i],section=packet.slice(header.index+header[0].length,headings[i+1]?.index??packet.indexOf("## CROSS-ITEM",header.index));
 assert(x.exercise_kind==="anchor"&&x.hint_steps.length>=2&&x.hint_steps.length<=3,"staged reviewed anchor "+x.exercise_id);
 const problem=section.match(/\*\*Đề bài\.\*\*\s*([\s\S]*?)\n\n\*\*Gợi ý/);
 const sol=section.match(/\*\*Lời giải(?: kiểm tra nội bộ)?\.\*\*\s*([\s\S]*?)(?=\n\n\*\*(?:Vì sao cách này|Rubric \/))/);
 assert(problem&&sol,"review packet parser "+x.exercise_id);
 assert.equal(x.problem_markdown,problem[1].trim(),"verbatim reviewed prompt "+x.exercise_id);
 assert.equal(x.full_solution_markdown,sol[1].trim(),"verbatim reviewed solution "+x.exercise_id);
 assert(x.hint_steps.every(h=>typeof h==="string"&&h.length>=20),"hint integrity "+x.exercise_id);
 assert(x.rubric.length>=4&&x.rubric.reduce((a,r)=>a+r.points,0)===x.rubric_total,"correct rubric "+x.exercise_id);
 assert(x.common_mistakes.length>=3,"pedagogical mistakes "+x.exercise_id);
 assert(x.remediation_links.length>=2&&x.remediation_links.every(l=>l.href.startsWith("../kien-thuc/")),"internal remediation "+x.exercise_id);
 assert(x.academic_review?.status==="APPROVED"&&x.academic_review.packet_id==="MATH-WRITTEN-GAP9-20261023-R0","review metadata "+x.exercise_id);
 assert(x.academic_review.publication_gate==="PENDING_OWNER_RELEASE","do not mislabel as owner approved");
 assert(x.gates_core===false&&x.auto_readiness_credit===false,"no readiness/mastery credit");
 assert(x.grade_overlay.length===1,"single intended grade overlay "+x.exercise_id);
 if(x.level!=="ENTRANCE10")assert(x.kntt_placements?.length===1&&x.kntt_placements[0].grade===x.grade_overlay[0],"S1 grade placement "+x.exercise_id);
 else assert(!x.kntt_placements,"Entrance10 transfer not cloned into grade lesson");
}
const batch=data.published_scope.batches.find(b=>b.batch_id==="GAP9_NEW_STRUCTURES_20261023");
assert(batch&&batch.count===9&&batch.status==="REVIEW_CANDIDATE_OWNER_RELEASE_PENDING","not an owner release decision");
assert.equal(data.exercises[75].problem_type_id,"g6-lcm-same-remainder-bounds");
assert(data.exercises.find(x=>x.exercise_id==="WX19-CIR-005").full_solution_markdown.includes("DE=12\\cos60"));
const overlay=JSON.parse(read("docs/assets/data/written-exercises/written-p2-hints-overlay-v1.json"));
assert.equal(overlay.source_catalog_exercise_count,84);
assert.equal(overlay.source_catalog_snapshot_date,data.snapshot_date);
assert.equal(overlay.changes.length,3,"preexisting P2 hints retained");
console.log("PASS GAP9: 9 exact reviewed question/solution pairs, 75-item historical hash, 84 unique IDs, S1 and P2 overlay boundaries");

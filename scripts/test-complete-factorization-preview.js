"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const crypto=require("node:crypto");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=file=>fs.readFileSync(path.join(root,file),"utf8");
const json=file=>JSON.parse(read(file));
const sha=body=>crypto.createHash("sha1").update("blob "+Buffer.byteLength(body)+"\0").update(body).digest("hex");
const prefix="docs/assets/data/curriculum/";
const c=json(prefix+"complete-factorization-preview-v1.json");
const bankPath="docs/assets/data/practice/"+c.source_file;
assert.equal(sha(read(bankPath)),c.source_file_blob_sha,"source question version drift");
const bank=json(bankPath);
const app=require("../docs/assets/javascripts/complete-factorization-preview-v1.js");
assert.ok(app.validConfig(c));
assert.equal(app.BUILD,"complete-factor-preview-v1-20260927");
const q=app.prepareItems(c,bank.questions);
assert.equal(q.length,8);
assert.deepEqual(q.map(x=>x.id),Array.from({length:8},(_,i)=>"FAC06V1_"+String(i+77).padStart(3,"0")));
assert.ok(q.every(x=>x.assessed_skill==="phan-tich-da-thuc-hoan-toan"));
assert.ok(q.every(x=>x.tags.skill.length===1&&x.tags.skill[0]==="phoi-hop-phuong-phap"));
assert.ok(q.every(x=>x.answer===0&&x.options.length===4));
const d=json(prefix+"primary-skill-decision-register-39-v1.json");
const rows=new Map(d.items.map(x=>[x.question_id,x]));
for(const item of q){
 const decision=rows.get(item.id);
 assert.ok(decision,item.id+" decision absent");
 assert.equal(decision.selected_assessed_skill_candidate,item.assessed_skill);
 assert.equal(decision.decision_status,"scoped_primary_candidate");
 assert.equal(decision.question_source_blob_sha,c.source_file_blob_sha);
 assert.equal(decision.runtime_enabled,false,"canonical decision register cannot be promoted silently");
}
const sh=app.shuffle([0,1,2,3],()=>0);
assert.deepEqual(sh.slice().sort(),[0,1,2,3],"shuffle must preserve original option IDs");
assert.deepEqual(app.summarize([{question:q[0],correct:true},{question:q[1],correct:false}]),{attempted:2,correct:1,wrong:[q[1].id]});
assert.equal(app.validConfig({...c,question_ids:[q[0].id,q[0].id,...c.question_ids.slice(2)]}),false,"duplicate config ids must be refused");
assert.throws(()=>app.prepareItems({...c,source_file:"../escape.json"},bank.questions));
assert.throws(()=>app.prepareItems(c,bank.questions.filter(x=>x.id!==q[0].id)));
const js=read("docs/assets/javascripts/complete-factorization-preview-v1.js");
assert.ok(!/\blocalStorage\b|\bsessionStorage\b|indexedDB|document\.cookie/.test(js),"preview may not read/write any learner stores");
assert.ok(!/appendEvidence|recordAnswer|record\(question/.test(js),"preview may not record mastery events");
assert.ok(!js.includes("primary-skill-decision-register-39-v1"),"preview cannot consume unapproved registry dynamically");
assert.ok(read("mkdocs.yml").includes("assets/javascripts/skill-assessment-pilot-v2.js"),"Beta v2 must remain installed");
assert.ok(read("mkdocs.yml").includes("assets/javascripts/complete-factorization-preview-v1.js"),"new opt-in preview must be registered");
assert.ok(read("docs/huong-dan/thu-nghiem-phan-tich-hoan-toan.md").includes("không lưu"),"must disclose no-storage behavior");
console.log("PASS eight source-locked CĐ06 questions map to one proposed *output-only* skill");
console.log("PASS no v1/v2 storage or mastery evidence access, config rejects malformed/duplicate IDs");
console.log("PASS preview code and Beta v2 coexist; no changes to legacy primary engine");
console.log("PASSED complete-factorization preview checks.");

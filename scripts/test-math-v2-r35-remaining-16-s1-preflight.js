#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {audit,SOURCE,SOURCE_BLOB,EXPECTED}=require("./prototypes/math-v2-r35-remaining-16-s1-preflight.js");
const {gitBlob}=require("./prototypes/math-v2-source-locked-skill-audit-r22.js");
const result=audit();
assert.equal(gitBlob(fs.readFileSync(SOURCE)),SOURCE_BLOB);
assert.equal(result.schema,"math-r35-remaining-16-source-review-preflight-v1");
assert.equal(result.exact_historical_R27_source_rows,16);
assert.equal(result.prior_owner_approved_excluded,24);
assert.deepEqual(result.unapproved_ids,EXPECTED);
assert.equal(result.original_sources_unchanged,true);
assert.equal(result.grade7_original_pages_independently_viewed_in_R35,false);
assert.equal(result.academic_pass_newly_authorized,0);
assert.equal(result.primary_layer_newly_authorized,0);
assert.equal(result.runtime_credit_authorized,false);
assert.equal(result.student_history_or_backfill_authorized,false);
assert.equal(result.production_change_authorized,false);
assert.equal(result.rows.length,16);
assert(result.rows.every(r=>r.original_answer===0));
const packet=fs.readFileSync(SOURCE,"utf8");
const invalid=packet.replace("### NUM02V1_133 — CT02","### NUM02V1_132 — CT02");
assert.throws(()=>audit({packetOverride:invalid}),/R35_ORDER_OR_APPROVAL_OVERLAP/);
const changed=packet.replace("Tính \\(-\\frac25+\\frac3{10}\\).","Tính \\(-\\frac25+\\frac4{10}\\).");
assert.notEqual(changed,packet);
assert.throws(()=>audit({packetOverride:changed}),/R35_R27_ITEM_CONTENT_CHANGED_NUM02V1_133/);
const wrongSGK=packet.replace("SGK Toán 7 Tập 1 KNTT, Bài 2:", "SGK Toán 9 Tập 1 KNTT, Bài 2:");
assert.throws(()=>audit({packetOverride:wrongSGK}),/R35_REVIEWER_CITATION_MISSING_NUM02V1_133/);
const code=fs.readFileSync("scripts/prototypes/math-v2-r35-remaining-16-s1-preflight.js","utf8");
assert(!/localStorage|indexedDB|sessionStorage|sendBeacon|writeFile|appendFile|unlinkSync|rmSync/.test(code));
console.log("PASS R35: source locked exactly 16 previously unapproved MCQs, R33 approved 24 untouched, no academic or learner writes");

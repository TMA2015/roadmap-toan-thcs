#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {audit,FILE,PIN,CT12}=require("./prototypes/math-v2-r33-owner-21-core-signoff.js");
const {gitBlob}=require("./prototypes/math-v2-source-locked-skill-audit-r22.js");
const result=audit();
assert.equal(gitBlob(fs.readFileSync(FILE)),PIN);
assert.equal(result.academic_approved_ids,21);
assert.equal(result.Core,21);
assert.deepEqual(result.evidence,{STRUCTURAL_CLONE:8,CONCEPT_BASE:13,EXACT_MATCH:0});
assert.deepEqual(result.pending,CT12);
assert.equal(result.release_authorized,false);
assert.equal(result.learner_writes,false);
const receipt=JSON.parse(fs.readFileSync(FILE,"utf8"));
const fakeApproval=structuredClone(receipt);
fakeApproval.CT12_pending_items[0].primary_layer_approved="Entrance10";
assert.throws(()=>audit({override:fakeApproval}),/R33_SIGNOFF_CT12_UNAUTHORIZED/);
const wrongId=structuredClone(receipt);
wrongId.approved_items[1].item_id=wrongId.approved_items[0].item_id;
assert.throws(()=>audit({override:wrongId}),/R33_SIGNOFF_ROW_/);
const wrongEvidence=structuredClone(receipt);
wrongEvidence.approved_items[0].evidence_type_approved="EXACT_MATCH";
assert.throws(()=>audit({override:wrongEvidence}),/R33_SIGNOFF_ROW_/);
const fakeRuntime=structuredClone(receipt);
fakeRuntime.academic_signoff_grants_runtime_skill_credit=true;
assert.throws(()=>audit({override:fakeRuntime}),/R33_SIGNOFF_BOUNDARIES_CHANGED/);
const fakeMerge=structuredClone(receipt);
fakeMerge.release_or_merge_authorized_by_this_receipt=true;
assert.throws(()=>audit({override:fakeMerge}),/R33_SIGNOFF_BOUNDARIES_CHANGED/);
const doc=fs.readFileSync("review-packets/math-phase4-r27-mcq-40/TEMP_R33_OWNER_ACADEMIC_21_CORE_SIGNOFF_20261018.md","utf8");
assert(doc.includes("OWNER APPROVED")&&doc.includes("NOT AUTHORIZED"));
const src=fs.readFileSync("scripts/prototypes/math-v2-r33-owner-21-core-signoff.js","utf8");
assert(!/localStorage|indexedDB|sessionStorage|sendBeacon|writeFile|appendFile|unlinkSync|rmSync/.test(src));
console.log("PASS R33 owner signoff: 21 Core academically approved (8 clone/13 concept), 3 CT12 held, no runtime/learner/merge authority");

#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8");
const prefix="review-packets/math-content-cleanup/";
const receipt=read(prefix+"MATH-CT05-07-W3A-WR-R1-20261016_NOTEBOOKLM_VERDICT_RECEIPT.md");
const gate=read(prefix+"MATH-CT05-07-W3A-WR-R2_IMPLEMENTATION_GATE.md");
const expected=["05-ENT-01","06-CH-01","07-WR-11"];
const lines=receipt.split("\n").filter(s=>/^(05-ENT-01|06-CH-01|07-WR-11) \| PASS \| PASS \| PASS \| PASS \|/.test(s));
assert.deepEqual(lines.map(x=>x.split("|")[0].trim()),expected);
assert(receipt.includes("PACKET_ID|MATH-CT05-07-W3A-WR-R1-20261016"));
assert(receipt.includes("EXPECTED=3")&&receipt.includes("REVIEWED=3"));
assert(receipt.includes("OVERALL|PASS_FOR_AUTHORING_REVIEW"));
assert(receipt.includes("MISSING_IDS|NONE")&&receipt.includes("DUPLICATE_IDS|NONE")&&receipt.includes("UNEXPECTED_IDS|NONE"));
assert(lines[0].includes("APPROVE_NEW_WX") && lines[1].includes("APPROVE_NEW_WX") && lines[2].includes("PLACE_CORE_ONLY"));
assert(gate.includes("NOT APPROVED / NO PRODUCTION CHANGE"),"historical pre-release gate receipt must remain immutable");
assert(gate.includes("Specialized-Challenge")&&gate.includes("pt07-core-2"));
const library=JSON.parse(read("docs/assets/data/written-exercises/written-exercise-library-v1.json"));
const published=library.exercises.filter(x=>["WX05-ENT-001","WX06-CH-001"].includes(x.exercise_id));
assert(library.exercises.length>=65,"W3A-WR release must preserve 63+2 historical entries");
assert.deepEqual(published.map(x=>x.exercise_id),["WX05-ENT-001","WX06-CH-001"],"exact source-to-WX one-to-one");
for(const x of published){
 assert.equal(x.academic_review?.packet_id,"MATH-CT05-07-W3A-WR-R1-20261016");
 assert.equal(x.rubric_total,4);
 assert.equal(x.rubric.reduce((a,r)=>a+r.points,0),4);
 assert.equal(x.hint_steps?.length,3);
 assert.equal(x.exercise_kind,"anchor");
}
assert.equal(published[0].learning_layer,"Entrance10");
assert.equal(published[1].learning_layer,"Specialized-Challenge");
assert.equal(published[1].level,"CHALLENGE");
assert.equal(published[1].learner_label,"Thử thách");
assert.equal(library.auto_readiness_credit,false);
assert.equal(library.self_marking_only,true);
assert(library.published_scope.exercise_count>=65,"W3A-WR historical count must not be reduced");
const core=JSON.parse(read("docs/assets/data/curriculum/topic07-learning-workspace.json"));
const existing=core.cards.find(c=>c.id==="pt07-core-2");
assert(existing,"Existing CT07 Core card must remain");
assert(existing.teaching_copy.key_idea.includes("miền xác định ban đầu"),"Original CT07 rule lost");
assert(existing.teaching_copy.misconception.includes("x-2"),"07-WR-11 domain explanation missing");
const test=read("scripts/test-written-exercise-library-v1.js");
assert(test.includes('"Specialized-Challenge"'),"Challenge schema guard missing");
const ui=read("docs/assets/javascripts/written-exercise-library-v1.js");
assert(ui.includes('["CHALLENGE","Thử thách"]'),"Challenge selector absent");
assert(!library.exercises.some(x=>x.exercise_id.startsWith("PROPOSED-")),"Draft IDs must not be published");
console.log("PASS W3A-WR exact reviewed release: 63+2 canonical items, optional Challenge, CT07 Core reuse, no readiness");

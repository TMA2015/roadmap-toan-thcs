#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8");
const prefix="review-packets/math-content-cleanup/";
const receipt=read(prefix+"MATH-CT05-07-W3A-WR-R1-20261016_NOTEBOOKLM_VERDICT_RECEIPT.md");
const gate=read(prefix+"MATH-CT05-07-W3A-WR-R2_IMPLEMENTATION_GATE.md");
const expected=["05-ENT-01","06-CH-01","07-WR-11"];
const lines=receipt.split("\n").filter(s=>/^(05-ENT-01|06-CH-01|07-WR-11) \| PASS \| PASS \| PASS \| PASS \|/.test(s));
assert.deepEqual(lines.map(x=>x.split("|")[0].trim()),expected);
assert(receipt.includes("PACKET_ID|MATH-CT05-07-W3A-WR-R1-20261016"));
assert(receipt.includes("EXPECTED=3")&&receipt.includes("REVIEWED=3"));
assert(receipt.includes("OVERALL|PASS_FOR_AUTHORING_REVIEW"));
assert(receipt.includes("MISSING_IDS|NONE")&&receipt.includes("DUPLICATE_IDS|NONE")&&receipt.includes("UNEXPECTED_IDS|NONE"));
assert(lines[0].includes("APPROVE_NEW_WX") && lines[1].includes("APPROVE_NEW_WX") && lines[2].includes("PLACE_CORE_ONLY"));
assert(gate.includes("NOT APPROVED / NO PRODUCTION CHANGE"));
assert(gate.includes("Specialized-Challenge")&&gate.includes("pt07-core-2"));
const library=JSON.parse(read("docs/assets/data/written-exercises/written-exercise-library-v1.json"));
assert(!library.exercises.some(x=>["WX05-ENT-001","WX06-CH-001"].includes(x.exercise_id)),"New WX item published without owner QA");
assert.equal(library.exercises.length,63,"This document PR must not change the live written library");
const core=JSON.parse(read("docs/assets/data/curriculum/topic07-learning-workspace.json"));
const existing=core.cards.find(c=>c.id==="pt07-core-2");
assert(existing,"Existing CT07 Core card must remain");
assert(existing.teaching_copy.key_idea.includes("miền xác định ban đầu"),"Existing approved CT07 explanation lost");
const test=read("scripts/test-written-exercise-library-v1.js");
assert(test.includes('"KNTT-Core","Core-Support","Entrance10"'),"Challenge layer contract drift: reassess the implementation gate");
const ui=read("docs/assets/javascripts/written-exercise-library-v1.js");
assert(ui.includes('["ENTRANCE10","Ôn thi vào 10"]')&&ui.includes('["CHALLENGE","Thử thách"]'),"Optional Challenge filter must remain supported without releasing WX content");
console.log("PASS W3A-WR 3/3 submitted authoring verdict archived; Challenge UI supported; W3A-WR content still awaiting release");

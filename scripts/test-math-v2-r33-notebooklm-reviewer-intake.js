#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {audit,SOURCE,BLOB}=require("./prototypes/math-v2-r33-notebooklm-reviewer-intake.js");
const {gitBlob}=require("./prototypes/math-v2-source-locked-skill-audit-r22.js");
const r=audit();
assert.equal(gitBlob(fs.readFileSync(SOURCE)),BLOB);
assert.equal(r.input_ids,24);
assert.equal(r.reviewer_PASS,24);
assert.deepEqual(r.evidence_counts_from_table,{STRUCTURAL_CLONE:11,CONCEPT_BASE:13});
assert.equal(r.header_count_conflict,true);
assert.equal(r.matching_core_ids,21);
assert.deepEqual(r.CT12_provisional_ids,["QUA12V1_121","QUA12V1_122","QUA12V1_123"]);
assert.equal(r.math_R34_SHA_verified,true);
assert.equal(r.approved_academic_PASS,0);
assert.equal(r.approved_layer_changes,0);
assert.equal(r.student_data_writes,false);
const original=JSON.parse(fs.readFileSync(SOURCE,"utf8"));
const badCount=structuredClone(original);
badCount.table_type_counts.CONCEPT_BASE=12;
assert.throws(()=>audit({override:badCount}),/R33_REVIEW_SOURCE_AGGREGATES_MISMATCH/);
const promoted=structuredClone(original);
promoted.academic_owner_signoff=true;
assert.throws(()=>audit({override:promoted}),/R33_REVIEW_UNSUPPORTED_AUTHORITY_OR_SOURCE/);
const rewrite=structuredClone(original);
rewrite.rows[21].layer="KNTT-Core";
assert.throws(()=>audit({override:rewrite}),/R33_REVIEW_GRADE_SCOPE_CHANGED/);
const repeated=structuredClone(original);
repeated.rows[1].id=repeated.rows[0].id;
assert.throws(()=>audit({override:repeated}),/R33_REVIEW_ITEMS_OR_SOURCE_MISMATCH/);
const fakeS3=structuredClone(original);
fakeS3.S3_most_official_exams_claim_unverified=false;
assert.throws(()=>audit({override:fakeS3}),/R33_REVIEW_UNSUPPORTED_AUTHORITY_OR_SOURCE/);
const code=fs.readFileSync("scripts/prototypes/math-v2-r33-notebooklm-reviewer-intake.js","utf8");
assert(!/localStorage|indexedDB|sessionStorage|sendBeacon/.test(code));
assert(!/writeFile|appendFile|renameSync|unlinkSync|rmSync/.test(code));
console.log("PASS R33 NotebookLM intake: 24 rows, 11/13 actual vs 12/12 submitted, 21 Core agreements, 3 CT12 holds, no academic credit");

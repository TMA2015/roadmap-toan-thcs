#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),assert=require("node:assert/strict"),crypto=require("node:crypto");
const read=p=>fs.readFileSync(p,"utf8");
const catalogText=read("docs/assets/data/written-exercises/written-exercise-library-v1.json");
const bank=JSON.parse(catalogText);
const stage=JSON.parse(read("review-packets/written-exercise-library/MATH-WRITTEN-GAP3-20261023-STRUCTURED_CANDIDATES.json"));
const receipt=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP3-20261023-NOTEBOOKLM_OWNER_VERDICT.md");
const packet=read("review-packets/written-exercise-library/MATH-WRITTEN-GAP3-20261023-ONEPASS-NOTEBOOKLM.md");
const original84=JSON.stringify(bank.exercises.slice(0,84));
let h=0xcbf29ce484222325n;
for(let i=0;i<original84.length;i++)h=BigInt.asUintN(64,(h^BigInt(original84.charCodeAt(i)))*0x100000001b3n);
assert.equal(h.toString(16).padStart(16,"0"),"58d8ccf90fe283ff","original 84 historical items must remain identical");
assert.equal(bank.exercises.length,87);
assert.equal(bank.published_scope.exercise_count,87);
assert.equal(bank.auto_readiness_credit,false);
assert.equal(bank.self_marking_only,true);
assert.equal(new Set(bank.exercises.map(x=>x.exercise_id)).size,87);
assert.equal(stage.source_catalog_blob_sha,"85d8301daca7819009ba47eabf63080d586e9dc9");
assert.equal(stage.published_exercise_count,84);
assert.equal(stage.candidate_count,3);
assert.equal(stage.authorization,"REVIEW_ONLY_NO_DEPLOY");
assert.equal(stage.candidates.length,3);
assert(receipt.includes("PACKET_ID|MATH-WRITTEN-GAP3-20261023-R0"));
assert(receipt.includes("SOURCE_BLOB|85d8301daca7819009ba47eabf63080d586e9dc9"));
assert(receipt.includes("EXPECTED|3")&&receipt.includes("REVIEWED|3")&&receipt.includes("OVERALL|PASS"));
assert(receipt.includes("AUTHORIZATION|REVIEW_ONLY_NO_DEPLOY"),"academic receipt cannot itself authorize release");
const ids=["WX20-GEO-006","WX04-ALG-004","WX16-QUAD-005"];
const temporaryIds=["CAND-G6-AREA-01","CAND-G7-POLY-01","CAND-G8-MID-01"];
assert.deepEqual(bank.exercises.slice(84).map(x=>x.exercise_id),ids);
for(let i=0;i<3;i++){
  const x=bank.exercises[84+i],s=stage.candidates[i];
  assert.equal(s.candidate_id,temporaryIds[i]);
  assert(receipt.includes("ITEM|"+temporaryIds[i]+"|PASS"),"academic reviewer ID missing "+temporaryIds[i]);
  assert(packet.includes("## "+(i+1)+". "+temporaryIds[i]+" — "),"author source heading missing");
  for(const key of ["problem_markdown","hint_steps","full_solution_markdown","solution_steps","rubric","rubric_total","common_mistakes","remediation_markdown","method_rationale_markdown"])assert.deepEqual(x[key],s[key],"reviewed source drift "+x.exercise_id+"."+key);
  assert.equal(x.academic_review?.status,"APPROVED");
  assert.equal(x.academic_review?.packet_id,"MATH-WRITTEN-GAP3-20261023-R0");
  assert.equal(x.academic_review?.publication_gate,"OWNER_RELEASE_APPROVED_20261023");
  assert.equal(x.exercise_kind,"anchor");
  assert.equal(x.learning_layer,"KNTT-Core");
  assert.equal(x.hint_steps.length,3);
  assert.equal(x.rubric.reduce((n,r)=>n+r.points,0),x.rubric_total);
  assert.deepEqual(x.kntt_placements,[s.proposed_s1_placement]);
  assert.equal(x.gates_core,false);
  assert.equal(x.auto_readiness_credit,false);
  assert(x.remediation_links.length>=2);
  if(i===1)assert(x.figure_uri===null,"G7 algebra requires no illustration");
  else {
    assert(x.figure_uri&&x.figure_uri.startsWith("../assets/geometry/written-library/"));
    const fig="docs/"+x.figure_uri.replace(/^\.\.\//,"");
    assert(fs.existsSync(fig),"reviewed hypothesis-only SVG must exist "+fig);
    assert(read(fig).includes("<svg"),"not a valid SVG source "+fig);
  }
}
assert.equal(bank.exercises[84].kntt_placements[0].chapter,4,"Grade6 Bài20 belongs to Chapter IV, not III");
assert.equal(bank.exercises[85].kntt_placements[0].chapter,7);
assert.equal(bank.exercises[86].kntt_placements[0].chapter,4);
const old=bank.published_scope.batches;
assert.equal(old.at(-1).batch_id,"GAP3_NEW_STRUCTURES_20261023");
assert.equal(old.at(-1).count,3);
assert.equal(old.at(-1).status,"PUBLISHED");
assert.equal(old.at(-1).owner_release_authorization,"OWNER_APPROVED_RELEASE_20261023");
assert.equal(old.at(-2).batch_id,"GAP9_NEW_STRUCTURES_20261023");
const overlay=JSON.parse(read("docs/assets/data/written-exercises/written-p2-hints-overlay-v1.json"));
const sha=crypto.createHash("sha1").update("blob "+Buffer.byteLength(catalogText)+"\0").update(catalogText).digest("hex");
assert.equal(overlay.source_catalog_blob_sha,sha,"three legacy hint ladders source mismatch");
assert.equal(overlay.source_catalog_exercise_count,87);
assert.equal(overlay.changes.length,3);
assert.deepEqual(overlay.changes.map(x=>x.exercise_id).sort(),["WX07-RAT-001","WX16-QUAD-001","WX19-CIR-002"].sort());
assert(overlay.changes.every(x=>x.hint_steps.length===2),"previous P2 hints unchanged");
console.log("PASS GAP3 release: first 84 source-locked, 3 approved new items exact review, verified KNTT placements, 2 SVGs, old P2 hints preserved");
